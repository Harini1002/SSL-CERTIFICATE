import { GoogleGenAI, Type } from "@google/genai";
import { ScanResult, IncidentTicket, ChatMessage } from "../src/types.js";

let aiInstance: GoogleGenAI | null = null;

function getAiClient(): GoogleGenAI | null {
  if (!aiInstance) {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey || apiKey === "MY_GEMINI_API_KEY") {
      console.warn("GEMINI_API_KEY is not configured or uses default template value. AI mock fallback is enabled.");
      return null;
    }
    aiInstance = new GoogleGenAI({
      apiKey: apiKey,
      httpOptions: {
        headers: {
          "User-Agent": "aistudio-build"
        }
      }
    });
  }
  return aiInstance;
}

// 1. Generate incident tickets
export async function generateIncidentTicket(result: ScanResult): Promise<IncidentTicket> {
  const client = getAiClient();
  const ticketId = `INC-CERT-${Math.floor(100000 + Math.random() * 900000)}`;
  const nowStr = new Date("2026-06-09T09:58:12Z").toLocaleDateString();

  if (!client) {
    // Elegant deterministic backup template
    const urgency = result.riskLevel === "expired" || result.riskLevel === "critical" ? "P1" : result.riskLevel === "high" ? "P2" : "P3";
    return {
      id: ticketId,
      domain: result.domain,
      ticketSubject: `[${urgency}] SSL Certificate Expiry Critical Outage Risk: ${result.domain}`,
      ticketBody: `========================================\nCERTGUARD AI — SECURITY INCIDENT TICKET\n========================================\nTICKET ID     : ${ticketId}\nPRIORITY      : ${urgency} (Risk: ${result.riskLevel.toUpperCase()})\nSTATUS        : Open\nCREATED       : ${nowStr}\nASSIGNED TO   : SecOps Infrastructure Team\n========================================\n\nSUMMARY\n-------\nCritical outage exposure on resource ${result.domain} due to SSL certificate reaching lifecycle expiration threshold (${result.daysRemaining ?? "N/A"} days remaining).\n\nTECHNICAL SNAPSHOT\n------------------\n- Domain: ${result.domain}\n- CA Issuer: ${result.issuer}\n- Cert Expiration: ${result.expiryDate}\n- SSL Grade: ${result.sslGrade}\n- Signature Algorithm: ${result.signatureAlgorithm}\n- Serial Number: ${result.serialNumber}\n\nBUSINESS OUTAGE IMPACT\n----------------------\nOutage of SSL certificates triggers full browser privacy blocks ('Your connection is not private'). Complete lockout of client traffic, API service failures, compliance violations under SOC2/PCI-DSS, and degradation of public user trust.\n\nTECHNICAL REMEDIATION RUNBOOK\n-----------------------------\n1. Trigger instant renewal request from current CA (${result.issuer}).\n2. Re-verify DNS Control panel and API authentication challenges (HTTP-01 or DNS-01).\n3. Install new certificate chains onto the target load balancers, CDN endpoints, and target hosts.\n4. Execute post-deployment checking to verify chain completeness.\n5. Log the new cert serial in inventory audits for multi-cycle warnings.\n\nGenerated by CertGuard AI DevSecOps Agent.`,
      urgencyLabel: urgency as any,
      remediationSteps: [
        `Trigger automated CA request challenge with current issuer: ${result.issuer}`,
        "Complete Domain validation challenge (DNS TXT or ACME well-known folder verification)",
        "Download latest TLS/SSL PEM bundle containing critical cross-signed intermediates",
        "Perform secure hot-reload deployment across local and cloud balancer fleets"
      ],
      prediction: `Based on previous patterns, this certificate is predicted to require renewal every 90 days. Next manual cycle estimated around September 2026.`,
      createdAt: new Date().toISOString()
    };
  }

  try {
    const response = await client.models.generateContent({
      model: "gemini-3.5-flash",
      contents: `Generate a professional, structured DevSecOps ITIL Incident Ticket for this certificate issue:\nDomain: ${result.domain}\nDays Remaining: ${result.daysRemaining ?? "N/A"}\nExpiry Date: ${result.expiryDate}\nCA Issuer: ${result.issuer}\nRisk Level: ${result.riskLevel}\nGrade: ${result.sslGrade}\nAlgorithm: ${result.signatureAlgorithm}`,
      config: {
        systemInstruction: "You are a Senior DevSecOps Incident Response Coordinator. Generate highly structured, actionable, and executive-level ITIL incident tickets in JSON format.",
        responseMimeType: "application/json",
        responseSchema: {
          type: Type.OBJECT,
          properties: {
            ticketSubject: { type: Type.STRING },
            ticketBody: { type: Type.STRING },
            urgencyLabel: { type: Type.STRING, enum: ["P1", "P2", "P3", "P4"] },
            remediationSteps: {
              type: Type.ARRAY,
              items: { type: Type.STRING }
            },
            prediction: { type: Type.STRING }
          },
          required: ["ticketSubject", "ticketBody", "urgencyLabel", "remediationSteps", "prediction"]
        }
      }
    });

    const bodyText = response.text || "{}";
    const data = JSON.parse(bodyText.trim());

    return {
      id: ticketId,
      domain: result.domain,
      ticketSubject: data.ticketSubject || `[${data.urgencyLabel || "P1"}] SSL Expiry Warning: ${result.domain}`,
      ticketBody: data.ticketBody || "No details provided",
      urgencyLabel: (data.urgencyLabel as any) || "P1",
      remediationSteps: data.remediationSteps || [],
      prediction: data.prediction || "Expected lapse in 365 days.",
      createdAt: new Date().toISOString()
    };
  } catch (error) {
    console.error("Gemini ticket generation error, falling back:", error);
    // Return safety fallback ticket
    return generateIncidentTicket(result); // Recursive call will safely resolve inside mock fallback above
  }
}

